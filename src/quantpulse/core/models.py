"""Core domain data models for QuantPulse."""

import uuid
from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from quantpulse.core.types import OrderSide, OrderStatus, OrderType, TimeInForce


class Tick(BaseModel):
    """Real-time market tick representation."""

    model_config = ConfigDict(frozen=True)

    symbol: str
    timestamp: datetime
    bid_price: float = Field(ge=0.0)
    ask_price: float = Field(ge=0.0)
    bid_size: float = Field(default=0.0, ge=0.0)
    ask_size: float = Field(default=0.0, ge=0.0)
    last_price: float = Field(default=0.0, ge=0.0)
    last_size: float = Field(default=0.0, ge=0.0)
    volume: float = Field(default=0.0, ge=0.0)

    @property
    def mid_price(self) -> float:
        """Calculate middle price between bid and ask."""
        return (self.bid_price + self.ask_price) / 2.0

    @property
    def spread(self) -> float:
        """Calculate bid-ask spread."""
        return max(0.0, self.ask_price - self.bid_price)


class Bar(BaseModel):
    """OHLCV candlestick bar representation."""

    model_config = ConfigDict(frozen=True)

    symbol: str
    timestamp: datetime
    open: float = Field(gt=0.0)
    high: float = Field(gt=0.0)
    low: float = Field(gt=0.0)
    close: float = Field(gt=0.0)
    volume: float = Field(default=0.0, ge=0.0)
    vwap: float | None = None

    @property
    def typical_price(self) -> float:
        """Calculate typical price (High + Low + Close) / 3."""
        return (self.high + self.low + self.close) / 3.0

    @property
    def range(self) -> float:
        """Calculate bar price range (High - Low)."""
        return max(0.0, self.high - self.low)


class Order(BaseModel):
    """Trade order placed by strategy or portfolio."""

    model_config = ConfigDict(validate_assignment=True)

    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    symbol: str
    side: OrderSide
    order_type: OrderType
    quantity: float = Field(gt=0.0)
    price: float | None = Field(default=None, ge=0.0)  # Limit price
    stop_price: float | None = Field(default=None, ge=0.0)  # Stop loss price
    time_in_force: TimeInForce = Field(default=TimeInForce.GTC)
    status: OrderStatus = Field(default=OrderStatus.PENDING)
    filled_quantity: float = Field(default=0.0, ge=0.0)
    avg_fill_price: float = Field(default=0.0, ge=0.0)
    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def remaining_quantity(self) -> float:
        """Remaining unfilled order quantity."""
        return max(0.0, self.quantity - self.filled_quantity)

    @property
    def is_active(self) -> bool:
        """Check if order is currently active in the market."""
        return self.status in (
            OrderStatus.PENDING,
            OrderStatus.SUBMITTED,
            OrderStatus.PARTIALLY_FILLED,
        )


class ExecutionReport(BaseModel):
    """Report generated by broker upon trade fill or execution event."""

    model_config = ConfigDict(frozen=True)

    order_id: str
    exec_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    symbol: str
    side: OrderSide
    filled_quantity: float = Field(gt=0.0)
    fill_price: float = Field(gt=0.0)
    fee: float = Field(default=0.0, ge=0.0)
    slippage: float = Field(default=0.0)
    timestamp: datetime
    status: OrderStatus = Field(default=OrderStatus.FILLED)
    is_maker: bool = Field(default=False)


class PositionLot(BaseModel):
    """Specific tax-lot for FIFO cost-basis accounting."""

    model_config = ConfigDict(frozen=True)

    lot_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    symbol: str
    side: OrderSide
    quantity: float = Field(gt=0.0)
    entry_price: float = Field(gt=0.0)
    entry_time: datetime


class Position(BaseModel):
    """Aggregate position for a single asset."""

    model_config = ConfigDict(validate_assignment=True)

    symbol: str
    quantity: float = Field(default=0.0)  # Positive for long, negative for short
    avg_price: float = Field(default=0.0, ge=0.0)
    current_price: float = Field(default=0.0, ge=0.0)
    realized_pnl: float = Field(default=0.0)
    unrealized_pnl: float = Field(default=0.0)
    lots: list[PositionLot] = Field(default_factory=list)

    @property
    def is_long(self) -> bool:
        return self.quantity > 1e-9

    @property
    def is_short(self) -> bool:
        return self.quantity < -1e-9

    @property
    def is_flat(self) -> bool:
        return abs(self.quantity) <= 1e-9

    @property
    def market_value(self) -> float:
        """Current gross market value of the position."""
        return abs(self.quantity) * self.current_price

    @property
    def unrealized_pnl_pct(self) -> float:
        """Percentage return on active position."""
        if abs(self.avg_price) < 1e-9 or self.is_flat:
            return 0.0
        if self.is_long:
            return (self.current_price - self.avg_price) / self.avg_price
        else:
            return (self.avg_price - self.current_price) / self.avg_price


class PortfolioState(BaseModel):
    """Snapshot of portfolio accounting at a point in time."""

    model_config = ConfigDict(frozen=True)

    timestamp: datetime
    cash: float
    equity: float
    initial_margin: float = 0.0
    maintenance_margin: float = 0.0
    gross_market_value: float = 0.0
    leverage: float = 0.0
    free_cash: float = 0.0
    open_positions_count: int = 0
    total_realized_pnl: float = 0.0
    total_unrealized_pnl: float = 0.0
